// A secret routed to a PLUGGABLE store is read from that store through its own ClusterSecretStore.
// Minting it here too would put a second, different value under the same name — a split brain that
// surfaces as an application authenticating with the wrong credential, days later and nowhere near
// here. Every managed cloud already skips these (buildSecrets' secretProvisionedNatively).
func TestHetznerVaultForSkipsSecretsOwnedByAPluggableStore(t *testing.T) {
	pc := &types.ProjectConfig{Provider: "hetzner", Secrets: []types.ProjectSecretConfig{
		{Name: "ours", Generate: true},
		{Name: "theirs", Provider: "doppler", Generate: true},
		{Name: "explicit-native", Provider: "native", Generate: true},
	}}
	got := HetznerVaultFor(pc)
	if got == nil || len(got.Secrets) != 2 {
		t.Fatalf("derived %v, want the two natively-provisioned secrets", got)
	}
	for _, s := range got.Secrets {
		if s.Name == "theirs" {
			t.Error("a doppler-owned secret would ALSO be minted in the platform Vault — two values under one name")
		}
	}
	// And a project whose ONLY secret belongs to a connector needs no Vault at all.
	only := &types.ProjectConfig{Provider: "hetzner", Secrets: []types.ProjectSecretConfig{
		{Name: "theirs", Provider: "doppler"},
	}}
	if v := HetznerVaultFor(only); v != nil {
		t.Errorf("a project with only connector-owned secrets installed a Vault: %v", v)
	}
}

// THE offer-parity invariant. The canvas offers `generate`, `length` and `special_chars` on every
// cloud; the four managed ones carry all three into their secret store. Dropping them here would
// present three switches that change nothing — the state offer-parity refuses, and the state this
// file's first draft was in.
func TestHetznerVaultCarriesTheSizingTheCanvasOffers(t *testing.T) {
	pc := &types.ProjectConfig{Provider: "hetzner", Secrets: []types.ProjectSecretConfig{
		{Name: "api-key", Generate: true, Length: 64, SpecialChars: true},
		{Name: "operator-supplied"},
	}}
	got := HetznerVaultFor(pc)
	if got == nil || len(got.Secrets) != 2 {
		t.Fatalf("derived %v", got)
	}
	if got.Secrets[0] != (HetznerVaultSecret{Name: "api-key", Generate: true, Length: 64, SpecialChars: true}) {
		t.Errorf("the generated secret's sizing was dropped: %+v", got.Secrets[0])
	}
	if got.Secrets[1].Generate {
		t.Errorf("a manual secret was marked generated: %+v", got.Secrets[1])
	}

	// And it must survive the ONE channel to the Job, in the grammar the runner parses.
	y, err := HetznerVaultBootstrapJobManifest(*got, "runner:v1")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !strings.Contains(y, "--secrets=api-key:64:1,operator-supplied:manual") {
		t.Errorf("the Job does not carry the declared sizing:\n%s", y)
	}
}

