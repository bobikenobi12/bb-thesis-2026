// The fact that gates the APPLY and the fact that gates the REAP must be the same one, or a deploy
// applies a store that the very next CleanupSkippedInfraServices deletes — an oscillation that reads
// as an intermittently-broken ESO.
func TestTheStoreApplyAndTheStoreReapReadTheSameFact(t *testing.T) {
	for _, wired := range []bool{true, false} {
		facts := &InfraFacts{Provider: "hetzner", HetznerInClusterVault: wired}
		if renders := clusterSecretStoreRenderSet(facts)[HetznerSecretStoreName]; renders != wired {
			t.Fatalf("HetznerInClusterVault=%v renders=%v — the reaper disagrees with the fact", wired, renders)
		}
		t.Setenv("PATH", t.TempDir())
		var out strings.Builder
		_ = EnsureHetznerSecretStore(facts, &out, io.Discard)
		attempted := out.Len() != 0
		if attempted != wired {
			t.Errorf("HetznerInClusterVault=%v: the apply %s while the reaper would %s it",
				wired, map[bool]string{true: "ran", false: "was skipped"}[attempted],
				map[bool]string{true: "keep", false: "delete"}[wired])
		}
	}
}

