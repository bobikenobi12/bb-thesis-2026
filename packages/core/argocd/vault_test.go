// The store is applied on the SAME retry rail as the four cloud stores, and gated on the same fact
// that decides whether it is reaped. A store applied where no Vault exists points at a Service that
// is not there and sits permanently invalid; a store NOT applied where one does exist leaves the
// kind undelivered behind a green ArgoCD.
func TestEnsureHetznerSecretStoreIsGatedOnTheVaultFact(t *testing.T) {
	for name, facts := range map[string]*InfraFacts{
		"no facts at all":             nil,
		"hetzner with no Vault wired": {Provider: "hetzner"},
		"another cloud entirely":      {Provider: "aws", IRSAExternalSecretsArn: "arn:x"},
	} {
		// No kubectl on PATH: if it tried to apply, it would fail rather than return nil.
		t.Setenv("PATH", t.TempDir())
		var out strings.Builder
		if err := EnsureHetznerSecretStore(facts, &out, io.Discard); err != nil {
			t.Errorf("%s: applied a store anyway: %v", name, err)
		}
		if out.Len() != 0 {
			t.Errorf("%s: %q", name, out.String())
		}
	}
}

