// THE cross-language invariant, and the one that fails in total silence.
//
// The vault chart names its Service after the Helm release; ArgoCD's release name is the Application
// name, which is `addon-` + the console's install-spec id. So hetznerVaultReleaseHost is not a name
// anyone gets to choose here — it is a CONSEQUENCE of the id and namespace the console mapper
// emitted. Get it wrong and nothing errors: the bootstrap Job's requests resolve nowhere, ESO's
// store never goes Valid, and the whole kind is quietly undelivered behind a green ArgoCD.
//
// The fixture is generated by the REAL mapper, so reading the id and namespace back out of it checks
// the actual TS contract rather than a string retyped in Go.
func TestHetznerVaultHostAgreesWithTheGeneratedFixture(t *testing.T) {
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate this file")
	}
	path := filepath.Join(filepath.Dir(thisFile), "..", "..", "..", "test", "e2e", "fixtures", "hetzner_data_services.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Skipf("generated fixture not present (%v)", err)
	}
	var fx struct {
		AddOns []struct {
			ID        string `json:"id"`
			Chart     string `json:"chart"`
			Namespace string `json:"namespace"`
		} `json:"addons"`
	}
	if err := json.Unmarshal(raw, &fx); err != nil {
		t.Fatalf("parse fixture: %v", err)
	}
	found := 0
	for _, a := range fx.AddOns {
		if a.Chart != "vault" {
			continue
		}
		found++
		want := AddOnAppName(a.ID) + "." + a.Namespace + ".svc.cluster.local:8200"
		if hetznerVaultReleaseHost != want {
			t.Errorf("hetznerVaultReleaseHost = %q, but the console renders install spec %q into namespace %q, "+
				"which ArgoCD syncs as Helm release %q — so the Service is at %q. A mismatch does not error: it resolves "+
				"nowhere, and the only symptom is a ClusterSecretStore that never goes Valid",
				hetznerVaultReleaseHost, a.ID, a.Namespace, AddOnAppName(a.ID), want)
		}
		if a.Namespace != hetznerVaultNamespace {
			t.Errorf("the chart installs into namespace %q but the bootstrap Job, its RBAC and the state Secret all live in %q — "+
				"the Job would run in a namespace with no Vault in it", a.Namespace, hetznerVaultNamespace)
		}
	}
	if found != 1 {
		t.Errorf("the fixture carries %d vault spec(s), want exactly 1 — every `secret` node on a project is a KV entry in the SAME Vault, "+
			"so a second release would be a second, unseeded, unreferenced Vault", found)
	}
}

func hetznerSecretProject(names ...string) *types.ProjectConfig {
	pc := &types.ProjectConfig{Provider: "hetzner"}
	for _, n := range names {
		pc.Secrets = append(pc.Secrets, types.ProjectSecretConfig{Name: n, Generate: true, Length: 32})
	}
	return pc
}

// THE naming invariant, and the one that fails silently.
//
// CleanupSkippedInfraServices reaps every name in categories.AllSaaSStoreNames() except the
// currently-selected connector's. `secretstore-vault` is in that set — it is the PLUGGABLE store for
// a Vault the CUSTOMER supplies. Naming the in-cluster store that would have it `kubectl delete`d on
// every deploy where no vault connector is chosen, and ESO would simply stop resolving with nothing
// in the job log to explain it.
func TestHetznerSecretStoreNameIsNotInTheSaaSReapSet(t *testing.T) {
	for _, name := range categories.AllSaaSStoreNames() {
		if name == HetznerSecretStoreName {
			t.Fatalf("the in-cluster store is named %q, which CleanupSkippedInfraServices reaps whenever "+
				"no matching SaaS connector is selected — pick a name outside AllSaaSStoreNames()", name)
		}
	}
	// It belongs to the per-cloud family instead, which is what it actually is.
	if !strings.HasPrefix(HetznerSecretStoreName, "secretstore-") {
		t.Errorf("store name %q leaves the per-cloud family convention", HetznerSecretStoreName)
	}
}

// A store in the per-cloud family MUST be in the esoStores reap map, or it is orphaned in a
// permanently-broken state when its Vault goes away — the exact failure that map exists to prevent.
func TestHetznerSecretStoreIsReapedWhenTheVaultIsGone(t *testing.T) {
	// Wired: the store renders, so it must NOT be reaped.
	keep := clusterSecretStoreRenderSet(&InfraFacts{Provider: "hetzner", HetznerInClusterVault: true})
	if !keep[HetznerSecretStoreName] {
		t.Error("the store does not render even though the in-cluster Vault is wired — it would be reaped")
	}
	// Not wired (no secret declared): it must be reaped rather than left pointing at nothing.
	drop := clusterSecretStoreRenderSet(&InfraFacts{Provider: "hetzner", HetznerInClusterVault: false})
	if drop[HetznerSecretStoreName] {
		t.Error("a store whose Vault is absent still renders — it would sit permanently broken")
	}
	// And on another cloud it is never rendered, so it is always reaped there.
	other := clusterSecretStoreRenderSet(&InfraFacts{Provider: "aws", IRSAExternalSecretsArn: "arn:x"})
	if other[HetznerSecretStoreName] {
		t.Error("the hetzner store renders on aws")
	}
	// The store must be KNOWN to the reaper at all — a name absent from the set is never reaped,
	// which is the orphan case this map exists to prevent.
	if _, known := drop[HetznerSecretStoreName]; !known {
		t.Error("the store is not in the reap set at all, so nothing would ever clean it up")
	}
}

func TestHetznerVaultForOnlyWhenHetznerAndSecretsExist(t *testing.T) {
	if got := HetznerVaultFor(hetznerSecretProject("api-key")); got == nil || len(got.Secrets) != 1 {
		t.Fatalf("a hetzner project with a secret derived %v", got)
	}
	// A Vault nobody asked for costs volumes and an audit surface for nothing.
	if got := HetznerVaultFor(hetznerSecretProject()); got != nil {
		t.Errorf("a project with no secrets derived a Vault: %v", got)
	}
	for _, provider := range []string{"aws", "gcp", "azure", "alibaba"} {
		pc := hetznerSecretProject("api-key")
		pc.Provider = types.CloudProvider(provider)
		if got := HetznerVaultFor(pc); got != nil {
			t.Errorf("%s derived an in-cluster Vault — it has a real cloud secret store", provider)
		}
	}
	if got := HetznerVaultFor(nil); got != nil {
		t.Errorf("a nil project derived %v", got)
	}
}

