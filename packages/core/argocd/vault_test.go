func TestEnsureHetznerVaultDeletesTheStaleJobThenApplies(t *testing.T) {
	stub := newKubectlStub(t, 0)
	v := HetznerVaultFor(hetznerSecretProject("api-key"))

	if err := EnsureHetznerVault(context.Background(), v, "runner:v1", io.Discard, io.Discard); err != nil {
		t.Fatalf("EnsureHetznerVault: %v", err)
	}
	deleted, applied := -1, -1
	for i, c := range stub.calls() {
		if strings.Contains(c, "delete job") {
			deleted = i
		}
		if strings.Contains(c, "apply") {
			applied = i
		}
	}
	// Re-applying a completed Job fails on immutable fields, so without the delete a re-deploy never
	// re-runs the unseal step — and a Vault that restarted would stay sealed behind a green deploy.
	if deleted == -1 || applied == -1 || deleted > applied {
		t.Fatalf("calls = %v, want the stale Job deleted before the apply", stub.calls())
	}
}

