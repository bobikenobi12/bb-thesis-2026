// No credential may reach the container through argv or env: argv is world-readable via /proc and
// env shows in `kubectl describe pod`. The Job carries only NAMES; every value is read or written
// through the Kubernetes API from inside the pod.
func TestHetznerVaultJobCarriesNoCredential(t *testing.T) {
	y, err := HetznerVaultBootstrapJobManifest(HetznerVault{Secrets: []HetznerVaultSecret{{Name: "api-key", Generate: true}}}, "runner:v1")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	for _, forbidden := range []string{"secretKeyRef", "VAULT_TOKEN", "unsealKey", "--token"} {
		if strings.Contains(y, forbidden) {
			t.Errorf("the Job manifest mentions %q — no credential may reach the container this way:\n%s", forbidden, y)
		}
	}
	if !strings.Contains(y, "runAsNonRoot: true") || !strings.Contains(y, "readOnlyRootFilesystem: true") {
		t.Error("the Job pod is not hardened")
	}
	if strings.Contains(y, "ClusterRole") {
		t.Error("the bootstrap binds a ClusterRole — it must be namespace-scoped")
	}
}

