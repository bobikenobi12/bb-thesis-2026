func TestHetznerVaultJobPassesEverySecretAndTheStoreCoordinates(t *testing.T) {
	y, err := HetznerVaultBootstrapJobManifest(HetznerVault{Secrets: []HetznerVaultSecret{{Name: "api-key", Generate: true}, {Name: "signing-key", Generate: true}}}, "runner:v1")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !strings.Contains(y, "--secrets=api-key:0:0,signing-key:0:0") {
		t.Errorf("the Job does not carry both secret names:\n%s", y)
	}
	// The ESO credential the Job writes and the store's auth.secretRef must name the SAME Secret and
	// key, in the SAME namespace — a mismatch authenticates nothing and resolves nothing, silently.
	store := HetznerSecretStoreManifest()
	for _, want := range []string{HetznerSecretStoreCredSecret, hetznerSecretStoreCredKey, secretsSaaSNamespaceForStore} {
		if !strings.Contains(y, want) {
			t.Errorf("the Job does not mention %q", want)
		}
		if !strings.Contains(store, want) {
			t.Errorf("the ClusterSecretStore does not mention %q", want)
		}
	}
	// And the mount the bootstrap enables must be the path the store reads.
	if !strings.Contains(store, `path: "`+hetznerVaultKVMount+`"`) {
		t.Errorf("the store does not read the mount the bootstrap enables:\n%s", store)
	}
}

