// ── the icon gate ─────────────────────────────────────────────────────────────
// Declared above the generator body because `--self-test` drives it without ever reaching the
// manifest read or the two writes below.

/** The remedy printed under a refusal — one place, so the message and its self-test agree. */
const ICON_REMEDY =
	"Add the asset under packages/assets/static/icons/<slug>/<slug>-32x32.png (and -16x16.png),\n" +
	'or set "icon_url": null to declare that no mark ships for this connector — the console\n' +
	"renders a monogram tile for a null icon and issues no request for it.";

/**
 * Resolves a manifest `icon_url` against the committed asset root, returning `{ path }` — the
 * public path, or `null` for a declared absence — or `{ reason }` naming why it does not resolve.
 *
 * A dangling path is worse than no path: it is emitted into the TS registry AND persisted into
 * `connectors.icon_url`, so every render of every connector surface issues a request that 404s and
 * recovers into the monogram fallback. "No mark ships for this connector" must therefore be
 * spelled `null` in the manifest, not spelled as a path to a file nobody added.
 */
function resolveIconUrl(iconUrl, root) {
	if (iconUrl === undefined || iconUrl === null || iconUrl === "") {
		return { path: null };
	}
	if (typeof iconUrl !== "string") {
		return { reason: `icon_url must be a string or null, got ${typeof iconUrl}` };
	}
	if (!iconUrl.startsWith("/")) {
		return {
			reason: `icon_url ${JSON.stringify(iconUrl)} must be an absolute public path (start with "/")`,
		};
	}
	const rel = normalize(iconUrl.slice(1));
	if (rel.startsWith("..")) {
		return { reason: `icon_url ${JSON.stringify(iconUrl)} escapes packages/assets/static` };
	}
	if (!existsSync(join(root, rel))) {
		return {
			reason: `icon_url ${JSON.stringify(iconUrl)} resolves to no committed file (packages/assets/static/${rel})`,
		};
	}
	return { path: iconUrl };
}

/**
 * Resolves every catalog row's icon, keyed by slug. Returns one `slug: reason` line per offender —
 * ALL of them, so a manifest carrying eleven dangling paths is one fix rather than eleven runs.
 *
 * Keying by slug is the uniqueness the catalog already relies on (`getConnectorProviderBySlug`
 * looks a provider up by slug alone, and the seed's `ON CONFLICT (slug)` collapses a repeat), so a
 * duplicate is reported here rather than silently handing one row the other's icon.
 */
function gateIcons(rowsToGate, root) {
	const resolvedIcons = new Map();
	const failures = [];
	// Tracked apart from `resolvedIcons`, which a REFUSED row never enters — otherwise a duplicate
	// of a row that already failed would read as a first sighting and go unreported.
	const seen = new Set();
	for (const row of rowsToGate) {
		if (seen.has(row.slug)) {
			failures.push(`${row.slug}: duplicate slug — the catalog treats a slug as unique`);
			continue;
		}
		seen.add(row.slug);
		const resolved = resolveIconUrl(row.icon_url, root);
		if (resolved.reason !== undefined) {
			failures.push(`${row.slug}: ${resolved.reason}`);
			continue;
		}
		resolvedIcons.set(row.slug, resolved.path);
	}
	return { icons: resolvedIcons, failures };
}

// ── --self-test ───────────────────────────────────────────────────────────────
// The gate's REFUSAL is the half worth proving. A guard whose "nothing found" branch is
// indistinguishable from "nothing wrong" is worth nothing, so these cases drive the failing
// branch against a hand-built asset tree and assert on WHICH slug is named, not on a count. The
// tree is built here rather than pointed at packages/assets/static, so a pass is not merely
// agreement with whatever happens to be committed today — the real catalog is a separate,
// explicitly labelled positive control at the end.

/** Runs the icon gate's self-test. Returns true if every case passed. */
function selfTest() {
	let failed = 0;
	const check = (label, fn) => {
		try {
			fn();
			console.log(`ok   - ${label}`);
		} catch (err) {
			failed += 1;
			console.log(`FAIL - ${label}\n       ${err.message}`);
		}
	};
	const eq = (actual, expected, what) => {
		const a = JSON.stringify(actual);
		const e = JSON.stringify(expected);
		if (a !== e) throw new Error(`${what ?? "value"}: expected ${e}, got ${a}`);
	};
	const has = (actual, needle) => {
		if (typeof actual !== "string" || !actual.includes(needle)) {
			throw new Error(`expected ${JSON.stringify(actual)} to contain ${JSON.stringify(needle)}`);
		}
	};

	const fake = mkdtempSync(join(tmpdir(), "alethia-icons-"));
	try {
		mkdirSync(join(fake, "icons", "vault"), { recursive: true });
		writeFileSync(join(fake, "icons", "vault", "vault-32x32.png"), "stand-in for a png");
		mkdirSync(join(fake, "digitalocean"), { recursive: true });
		writeFileSync(join(fake, "digitalocean", "favicon_64x64.png"), "stand-in for a png");

		check("a path with a file behind it resolves", () =>
			eq(resolveIconUrl("/icons/vault/vault-32x32.png", fake), {
				path: "/icons/vault/vault-32x32.png",
			}),
		);
		check("...including one outside icons/ — the cloud favicons live at the tree root", () =>
			eq(resolveIconUrl("/digitalocean/favicon_64x64.png", fake), {
				path: "/digitalocean/favicon_64x64.png",
			}),
		);
		check("a path with NO file behind it is refused, naming the path it looked for", () => {
			const r = resolveIconUrl("/icons/harbor/harbor-32x32.png", fake);
			has(r.reason, "/icons/harbor/harbor-32x32.png");
			has(r.reason, "no committed file");
		});
		check("...and one character off is still a refusal, not a declared absence", () =>
			has(resolveIconUrl("/icons/vault/vault-32x33.png", fake).reason, "no committed file"),
		);
		check("an explicit null is a declared absence, not a failure", () =>
			eq(resolveIconUrl(null, fake), { path: null }),
		);
		check("...and so are an absent key and an empty string", () => {
			eq(resolveIconUrl(undefined, fake), { path: null });
			eq(resolveIconUrl("", fake), { path: null });
		});
		check("a relative path is refused — the value is served as a public URL", () =>
			has(resolveIconUrl("icons/vault/vault-32x32.png", fake).reason, "absolute public path"),
		);
		check("a path that climbs out of the asset root is refused", () =>
			// The escape route that matters: an app's public/ tree is GENERATED by
			// sync-public-assets.mjs, so a file reachable only from there is not a file that ships.
			has(
				resolveIconUrl("/../../apps/console/public/icons/vault/vault-32x32.png", fake).reason,
				"escapes",
			),
		);
		check("a value that is not a string is refused", () =>
			has(resolveIconUrl(42, fake).reason, "must be a string or null"),
		);
		check("EVERY offender is named, not just the first", () => {
			const { failures } = gateIcons(
				[
					{ slug: "vault", icon_url: "/icons/vault/vault-32x32.png" },
					{ slug: "harbor", icon_url: "/icons/harbor/harbor-32x32.png" },
					{ slug: "quay", icon_url: "/icons/quay/quay-32x32.png" },
					{ slug: "doppler", icon_url: null },
				],
				fake,
			);
			eq(failures.length, 2, "failure count");
			const joined = failures.join("\n");
			has(joined, "harbor:");
			has(joined, "quay:");
			if (joined.includes("vault:") || joined.includes("doppler:")) {
				throw new Error(`a resolving row was reported: ${joined}`);
			}
		});
		check("a manifest whose icons all resolve or are declared null reports nothing", () => {
			const { icons: resolved, failures } = gateIcons(
				[
					{ slug: "vault", icon_url: "/icons/vault/vault-32x32.png" },
					{ slug: "harbor", icon_url: null },
				],
				fake,
			);
			eq(failures, []);
			eq(resolved.get("vault"), "/icons/vault/vault-32x32.png");
			eq(resolved.get("harbor"), null);
		});
		check("a REFUSED row reaches neither emitter", () => {
			// The registry emits `null` and the seed emits '' for a declared absence; both are falsy,
			// which is what every renderer branches on. A row that merely failed to resolve must not
			// be silently demoted into that same absence.
			const { icons: resolved, failures } = gateIcons(
				[{ slug: "gone", icon_url: "/icons/gone/gone-32x32.png" }],
				fake,
			);
			eq(failures.length, 1, "failure count");
			eq(resolved.has("gone"), false, "refused row present in the map");
		});
		check("a duplicate slug is reported — the map is keyed by it", () =>
			eq(
				gateIcons(
					[
						{ slug: "vault", icon_url: "/icons/vault/vault-32x32.png" },
						{ slug: "vault", icon_url: null },
					],
					fake,
				).failures,
				["vault: duplicate slug — the catalog treats a slug as unique"],
			),
		);
		check("...even when the FIRST sighting was itself refused", () => {
			const { failures } = gateIcons(
				[
					{ slug: "gone", icon_url: "/icons/gone/gone-32x32.png" },
					{ slug: "gone", icon_url: null },
				],
				fake,
			);
			eq(failures.length, 2, "failure count");
			has(failures[1], "duplicate slug");
		});
		check("an EMPTY asset tree refuses every path rather than passing", () => {
			const empty = mkdtempSync(join(tmpdir(), "alethia-icons-empty-"));
			try {
				has(
					resolveIconUrl("/icons/vault/vault-32x32.png", empty).reason,
					"no committed file",
				);
			} finally {
				rmSync(empty, { recursive: true, force: true });
			}
		});
		check("the positive control: the catalog as committed has no dangling icon", () => {
			const real = JSON.parse(readFileSync(manifestPath, "utf8"));
			const { failures } = gateIcons(
				[...(real.builtin ?? []), ...(real.providers ?? [])],
				assetsRoot,
			);
			eq(failures, []);
		});
		check("...and the remedy names both ways out", () => {
			has(ICON_REMEDY, "packages/assets/static/icons/");
			has(ICON_REMEDY, '"icon_url": null');
		});
	} finally {
		rmSync(fake, { recursive: true, force: true });
	}

	console.log(failed === 0 ? "\nself-test: all passed" : `\nself-test: ${failed} FAILED`);
	return failed === 0;
}

// ── modes ─────────────────────────────────────────────────────────────────────
// No argument generates. An unknown flag is an ERROR rather than a fall-through to the generator:
// a typo that silently regenerated would look exactly like a passing self-test.
const argv = process.argv.slice(2);
if (argv.length > 0) {
	if (argv.length === 1 && (argv[0] === "--help" || argv[0] === "-h")) {
		console.log(
			"gen-connectors.mjs            regenerate the registry + catalog seed from the manifest\n" +
				"gen-connectors.mjs --self-test  exercise the icon gate and exit",
		);
		process.exit(0);
	}
	if (argv.length === 1 && argv[0] === "--self-test") {
		process.exit(selfTest() ? 0 : 1);
	}
	console.error(`gen-connectors.mjs: unknown argument(s): ${argv.join(" ")}\nTry --help.`);
	process.exit(2);
}

/** Escapes a JS string literal value (single-quoted). */
function js(value) {
	return value === undefined || value === null
		? "undefined"
		: JSON.stringify(value);
}

/** Escapes a string for a single-quoted SQL literal. */
function sqlLiteral(value) {
	if (value === undefined || value === null) return "NULL";
	return `'${String(value).replace(/'/g, "''")}'`;
}

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const providers = manifest.providers ?? [];
// Built-in cloud/git connectors are catalog rows only (no module/credential
// schema): seeded into the `connectors` table but NOT emitted to the TS registry.
const builtin = manifest.builtin ?? [];
// Full catalog (all rows) for the SQL seed; providers alone drive the TS registry.
const catalogRows = [...builtin, ...providers];

// ── icon gate ─────────────────────────────────────────────────────────────────
// Every emitted icon_url must resolve, or be a declared null. Collect ALL offenders before
// failing so a manifest with eleven of them is one fix, not eleven runs.
const { icons, failures: iconFailures } = gateIcons(catalogRows, assetsRoot);
if (iconFailures.length > 0) {
	console.error(
		`✗ ${iconFailures.length} ${iconFailures.length === 1 ? "connector declares" : "connectors declare"} an icon_url that does not resolve:\n` +
			`${iconFailures.map((f) => `  ${f}`).join("\n")}\n\n${ICON_REMEDY}`,
	);
	process.exit(1);
}

// ── registry.generated.ts ─────────────────────────────────────────────────────
const ts = `${HEADER_TS}
/** Categories that support pluggable (non-cloud-native) connector backends. */
export const PLUGGABLE_CATEGORIES = ["dns", "secrets", "registry", "helm_registry", "observability"] as const;
export type PluggableCategory = (typeof PLUGGABLE_CATEGORIES)[number];

/** A single field collected for a credential or a component's provider_config. */
export interface ConnectorField {
	key: string;
	label: string;
	type: "text" | "password" | "boolean" | "select";
	secret?: boolean;
	required?: boolean;
	help?: string;
	default?: string | boolean;
	options?: string[];
}

export interface ConnectorProviderMeta {
	category: PluggableCategory;
	slug: string;
	name: string;
	description: string;
	organization: string;
	/** Public path to the connector's mark, or null when no mark ships (renders a monogram tile). */
	icon_url: string | null;
	docs_url?: string;
	status: "active" | "coming_soon";
	sort_order: number;
	modulePath: string;
	credentialFields: ConnectorField[];
	providerConfigFields: ConnectorField[];
}

export const CONNECTOR_PROVIDERS: ConnectorProviderMeta[] = [
${providers
	.map((p) => {
		const cred = p.credential?.fields ?? [];
		const cfg = p.provider_config?.fields ?? [];
		return `	{
		category: ${js(p.category)},
		slug: ${js(p.slug)},
		name: ${js(p.name)},
		description: ${js(p.description)},
		organization: ${js(p.organization)},
		icon_url: ${JSON.stringify(icons.get(p.slug) ?? null)},
		docs_url: ${js(p.docs_url)},
		status: ${js(p.status)},
		sort_order: ${p.sort_order},
		modulePath: ${js(p.module_path)},
		credentialFields: ${JSON.stringify(cred)},
		providerConfigFields: ${JSON.stringify(cfg)},
	},`;
	})
	.join("\n")}
];

/** Pluggable providers offered for a category (excludes the cloud-native default). */
export function getProvidersForCategory(category: PluggableCategory): ConnectorProviderMeta[] {
	return CONNECTOR_PROVIDERS.filter((p) => p.category === category);
}

/** Look up a provider by (category, slug), or undefined for the native default. */
export function getConnectorProvider(
	category: string,
	slug: string | null | undefined,
): ConnectorProviderMeta | undefined {
	if (!slug || slug === "native") return undefined;
	return CONNECTOR_PROVIDERS.find((p) => p.category === category && p.slug === slug);
}

/** Look up a provider by slug alone (slugs are globally unique in the catalog). */
export function getConnectorProviderBySlug(slug: string): ConnectorProviderMeta | undefined {
	return CONNECTOR_PROVIDERS.find((p) => p.slug === slug);
}
`;

mkdirSync(dirname(registryOut), { recursive: true });
writeFileSync(registryOut, ts);

// ── connectors.generated.sql ──────────────────────────────────────────────────
const rows = catalogRows
	.map((p) => {
		const cols = [
			sqlLiteral(p.slug),
			sqlLiteral(p.name),
			sqlLiteral(p.description),
			`${sqlLiteral(p.category)}::connector_category`,
			`${sqlLiteral(p.auth_method)}::connector_auth_method`,
			sqlLiteral(p.organization),
			// `connectors.icon_url` is NOT NULL (lib/db/schema/connectors.ts), so a declared absence
			// is seeded as the empty string rather than NULL. Every renderer branches on `!src`, so
			// '' and null behave identically at the UI: the monogram tile, and no request. Modelling
			// the absence as a real NULL needs a migration and is deliberately not done here.
			sqlLiteral(icons.get(p.slug) ?? ""),
			sqlLiteral(p.docs_url),
			`${sqlLiteral(p.status)}::connector_status`,
			String(p.sort_order),
		];
		return `  (${cols.join(", ")})`;
	})
	.join(",\n");

const sqlText = `${HEADER_SQL}
INSERT INTO connectors (slug, name, description, category, auth_method, organization, icon_url, docs_url, status, sort_order)
VALUES
${rows}
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name,
  description = EXCLUDED.description,
  category = EXCLUDED.category,
  auth_method = EXCLUDED.auth_method,
  organization = EXCLUDED.organization,
  icon_url = EXCLUDED.icon_url,
  docs_url = EXCLUDED.docs_url,
  status = EXCLUDED.status,
  sort_order = EXCLUDED.sort_order,
  updated_at = now();
`;

mkdirSync(dirname(seedOut), { recursive: true });
writeFileSync(seedOut, sqlText);

const iconless = catalogRows.filter((p) => icons.get(p.slug) === null).length;
console.log(
	`✓ generated registry (${providers.length} pluggable) + seed (${catalogRows.length} connectors) → lib/connectors/registry.generated.ts + lib/db/seed/connectors.generated.sql`,
);
console.log(
	`  icons: ${catalogRows.length - iconless} resolved against packages/assets/static, ${iconless} declared null (monogram tile)`,
);
