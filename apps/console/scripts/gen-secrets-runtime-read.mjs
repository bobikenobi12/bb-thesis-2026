// Generate the TypeScript mirror of which secrets providers a cluster can actually read at runtime
// (packages/core/categories/secrets_*.go — the `saasSecretStore` / `keylessSecretStore` hooks).
//
// The canvas has to answer "if the user picks this store, will workloads resolve values from it?"
// before it renders the picker, and until #1621 the answer was a hand-written TS list of two slugs
// (`SECRETS_NO_RUNTIME_READ`) with nothing tying it to the Go hooks that decide it. They agreed, and
// nothing made them keep agreeing — in the direction that matters, a list gone stale lets the user
// select a store the cluster will never resolve, and the failure surfaces at deploy time as
// unresolved secrets instead of at config time. That is the exact class `wave:offer-parity` (#1419)
// exists to make un-mergeable.
//
// GENERATED rather than hand-mirrored on purpose, and for the same reason as
// gen-keyless-cells.mjs: a hand list detects drift at best; a generated one makes drift impossible.
// This one is about to churn — #1620 adds a saasSecretStore hook to infisical, and with a hand list
// the canvas goes on hiding Infisical until somebody remembers to edit it.
//
// Run: `pnpm -C apps/console run gen:secrets-runtime-read` (from apps/console).

import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import { readSecretsRuntimeRead } from "./lib/secrets-runtime-read.mjs";

const ROOT = "../..";
const CATEGORIES_DIR = `${ROOT}/packages/core/categories`;
const CATALOG = `${CATEGORIES_DIR}/catalog.json`;
const OUT = "lib/connectors/generated/secrets-runtime-read.ts";

const hooks = readSecretsRuntimeRead(CATEGORIES_DIR);

/** Every `category: "secrets"` slug the console can offer — the totality anchor.
 *
 * catalog.json is what the picker renders FROM, so it is the set that must have an answer. Deriving
 * the totality from the Go registrations instead would be circular: a provider offered in the canvas
 * but registered nowhere would then be "complete" by construction, which is the hole. */
const catalogSlugs = JSON.parse(readFileSync(CATALOG, "utf8"))
	.providers.filter((p) => p.category === "secrets")
	.map((p) => p.slug);

// Fail BEFORE writing, not after. A slug missing from the table is read by the consumer as
// `undefined`, and `undefined` is not false — it would render as "selectable", the fail-OPEN
// direction. #1510 is the precedent: alibaba and hetzner came to be "excluded" by absence while the
// canvas went on offering them.
const unregistered = catalogSlugs.filter((s) => !hooks.has(s));
const uncatalogued = [...hooks.keys()].filter((s) => !catalogSlugs.includes(s));
if (unregistered.length > 0 || uncatalogued.length > 0) {
	const lines = [];
	if (unregistered.length > 0) {
		lines.push(
			`  offered in catalog.json but never register("secrets", …): ${unregistered.join(", ")}\n` +
				"    → the canvas offers a store with no behavior at all. Register it, or drop it from the catalog.",
		);
	}
	if (uncatalogued.length > 0) {
		lines.push(
			`  registered in Go but absent from catalog.json: ${uncatalogued.join(", ")}\n` +
				"    → a store the backend implements and the console cannot offer. Add the catalog entry.",
		);
	}
	console.error(
		`✗ secrets runtime-read — catalog.json and the Go registrations disagree:\n\n${lines.join("\n")}\n\n` +
			"Every offerable secrets store needs a runtime-read answer. A missing one is not a neutral\n" +
			"omission: the consumer reads absence as selectable.\n",
	);
	process.exit(1);
}

const q = (s) => JSON.stringify(s);
const body = catalogSlugs
	.map((slug) => {
		const h = hooks.get(slug);
		const why = h.length > 0 ? h.join(" + ") : "no store hook — renders nothing to read from";
		return `\t${q(slug)}: ${h.length > 0}, // ${why}`;
	})
	.join("\n");

const out = `// SPDX-FileCopyrightText: 2026 Alethia Labs <legal@alethialabs.io>
// SPDX-License-Identifier: AGPL-3.0-only

// GENERATED by apps/console/scripts/gen-secrets-runtime-read.mjs — DO NOT EDIT.
// Source of truth: packages/core/categories/secrets_*.go — a provider can be read in-cluster iff it
// registers \`saasSecretStore\` (credential-based ESO ClusterSecretStore) or \`keylessSecretStore\`
// (cross-account, the cluster's own workload identity). Registering one IS the definition; there is
// no separate declaration to keep in sync.
// Run \`pnpm -C apps/console run gen:secrets-runtime-read\` to regenerate.

/** Whether a cluster can resolve secrets from this store, keyed by connector slug.
 *
 * \`false\` is not "not built yet" in the harmless sense — selecting such a store is WORSE than doing
 * nothing. It flips \`secrets_provider\` off "native", so every per-cloud custom_secrets.tf stops
 * creating the native secrets, while no ClusterSecretStore renders to read from instead.
 *
 * Total over every \`category: "secrets"\` slug in catalog.json. Totality is the point: a slug nobody
 * thought about must not read as selectable. */
export const SECRETS_RUNTIME_READ: Record<string, boolean> = {
${body}
};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
const readable = catalogSlugs.filter((s) => hooks.get(s).length > 0).length;
console.log(
	`✓ secrets runtime-read → ${OUT} — ${readable} of ${catalogSlugs.length} store(s) readable in-cluster.`,
);
