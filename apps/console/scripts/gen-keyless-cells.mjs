// Generate the TypeScript mirror of `keylessCells` (packages/core/manifests/keyless.go).
//
// The canvas has to answer "will turning this toggle on produce a working keyless database?" before
// it renders the toggle. That question is the renderer's to answer — it is `keylessCellSupported` —
// and until #1510 the answer was not reachable from TypeScript at all, so the canvas offered keyless
// on every cloud × engine and three of those cells could not honor it.
//
// GENERATED rather than hand-mirrored on purpose. A hand list detects drift at best; a generated one
// makes drift impossible, and this table churns (aws × mysql and gcp × mysql opened four lanes after
// the table was first written). Same shape as catalog.json → generated/catalog.ts, and CI diff-checks
// the output the same way.
//
// Run: `pnpm -C apps/console run gen:keyless-cells` (from apps/console).

import { readFileSync, writeFileSync } from "node:fs";

import { readKeylessCells } from "./lib/keyless-cells.mjs";

const ROOT = "../..";
const CELLS_SRC = `${ROOT}/packages/core/manifests/keyless.go`;
const CATALOG_TS = "lib/cloud-providers/generated/catalog.ts";
const OUT = "lib/cloud-providers/generated/keyless-cells.ts";

const ENGINES = ["postgres", "mysql"];

/** The clouds a project can actually be placed on, read off the generated catalog's own slug union.
 *
 * This is the totality anchor the Go test cannot have: `CloudProviderSlug` is where "placeable cloud"
 * is actually defined, and it lives on the TypeScript side. Go's cloud_provider enum is wider (it
 * carries digitalocean and civo, which have no project template and therefore no keyless decision to
 * make yet), so checking against that would demand cells nobody can write. */
function placeableSlugs() {
	const src = readFileSync(CATALOG_TS, "utf8");
	const line = src.match(/export type CloudProviderSlug = Extract<CloudProvider,([^>]*)>/);
	if (!line) {
		throw new Error(
			`could not read CloudProviderSlug from ${CATALOG_TS} — the generator uses it as the set of ` +
				"clouds that must have a keyless decision. If the declaration moved, update this regex.",
		);
	}
	return [...line[1].matchAll(/"([a-z]+)"/g)].map((m) => m[1]);
}

const { cells } = readKeylessCells(CELLS_SRC);
const slugs = placeableSlugs();

// Fail before writing, not after: a hole here would emit a table the canvas silently reads as
// "unknown cloud → allowed", which is the fail-OPEN direction.
const holes = [];
for (const cloud of slugs) {
	for (const engine of ENGINES) {
		if (!cells.some((c) => c.cloud === cloud && c.engine === engine)) {
			holes.push(`${cloud} × ${engine}`);
		}
	}
}
if (holes.length > 0) {
	console.error(
		`✗ keyless cells — ${holes.length} placeable cloud × engine cell(s) have no entry in ` +
			`packages/core/manifests/keyless.go:\n\n${holes.map((h) => `    ${h}`).join("\n")}\n\n` +
			"Every cloud a project can be placed on needs a keyless decision — live, pending, or excluded\n" +
			"with the reason a user reads. A missing cell is not a neutral omission: it is how alibaba and\n" +
			"hetzner came to be 'excluded' by absence while the canvas went on offering them (#1510).\n",
	);
	process.exit(1);
}

const q = (s) => JSON.stringify(s);
const placeable = cells.filter((c) => slugs.includes(c.cloud));

const body = slugs
	.map((cloud) => {
		const rows = ENGINES.map((engine) => {
			const cell = placeable.find((c) => c.cloud === cloud && c.engine === engine);
			const reason = cell.state === "live" ? "" : `, reason: ${q(cell.reason)}`;
			return `\t\t${engine}: { state: ${q(cell.state)}${reason} },`;
		}).join("\n");
		return `\t${cloud}: {\n${rows}\n\t},`;
	})
	.join("\n");

const out = `// SPDX-FileCopyrightText: 2026 Alethia Labs <legal@alethialabs.io>
// SPDX-License-Identifier: AGPL-3.0-only

// GENERATED by apps/console/scripts/gen-keyless-cells.mjs — DO NOT EDIT.
// Source of truth: packages/core/manifests/keyless.go (\`var keylessCells\`), the renderer that decides
// whether a keyless database binding renders a proxy or fails closed.
// Run \`pnpm -C apps/console run gen:keyless-cells\` to regenerate.

import type { CloudProviderSlug, EngineFamily } from "./catalog";

/** What we claim about one cloud × engine keyless cell.
 *
 *   live     — every leg is built; the binding renders.
 *   pending  — a leg is missing; \`reason\` names the lane that will deliver it.
 *   excluded — the cloud can never honor it; \`reason\` is the product-voice why.
 *
 * \`pending\` and \`excluded\` are not interchangeable: the first is debt a lane retires, the second is a
 * permanent product boundary. Collapsing them is how a cloud gets excluded by simply being absent.
 */
export type KeylessCellState = "live" | "pending" | "excluded";

export interface KeylessCell {
	state: KeylessCellState;
	/** Present on every non-live cell. This string is USER-FACING on three surfaces — the canvas's
	 * disabled IAM-auth toggle, the deploy-time refusal, and the offer-parity matrix. */
	reason?: string;
}

/** Total over every placeable cloud × both engine families. Totality is the point: a cell nobody
 * thought about must not read as "allowed". */
export const KEYLESS_CELLS: Record<
	CloudProviderSlug,
	Record<EngineFamily, KeylessCell>
> = {
${body}
};
`;

writeFileSync(OUT, out);
console.log(
	`✓ keyless cells → ${OUT} — ${placeable.length} cell(s) across ${slugs.length} placeable cloud(s).`,
);
